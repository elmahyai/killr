"""print.xtable from xtable 1.8-8 (LaTeX path used by proofs and ``toLatex``)."""

from __future__ import annotations

from typing import Any

from xtable.caption_replacement import Xtable
from xtable.format_c import format_c_vector
from xtable.sanitize import NA, Strings, sanitize
from xtable.sanitize_numbers import sanitize_numbers


def _as_strings(values: list[str], type_: str) -> list[str]:
    out = sanitize(Strings(values), type=type_)
    if isinstance(out, Strings):
        return ["" if v is NA else str(v) for v in out]
    if isinstance(out, str):
        return [out]
    return [str(v) for v in out]


def _digits_attr(x: Xtable) -> Any:
    return x.attrs.get("digits", [0] * (x.ncol + 1))


def _display_attr(x: Xtable) -> list[str]:
    return list(x.attrs.get("display", ["f"] * (x.ncol + 1)))


def _align_attr(x: Xtable) -> list[str]:
    return list(x.attrs.get("align", ["l"] * (x.ncol + 1)))


def _format_cell(
    x: Xtable,
    r: int,
    c: int,
    *,
    type_: str,
    varying_digits: bool,
    digits_attr: Any,
    display_attr: list[str],
    decimal_mark: str,
    na_string: str,
    sanitize_text_function: Any,
    math_style_negative: bool,
    math_style_exponents: bool,
) -> str:
    val = x.data[r][c]
    col_vals = x.column(c + 1)
    is_numeric_col = all(
        isinstance(v, (int, float)) and not isinstance(v, bool)
        for v in col_vals
        if v is not None and not (isinstance(v, float) and v != v)
    )
    if val is None or (isinstance(val, float) and val != val):
        return na_string
    if isinstance(val, str):
        if sanitize_text_function is None:
            return _as_strings([val], type_)[0]
        return str(sanitize_text_function([val])[0])
    if is_numeric_col:
        if not varying_digits:
            fmt = "E" if digits_attr[c + 1] < 0 else display_attr[c + 1]
            dig = abs(int(digits_attr[c + 1]))
        else:
            fmt = "E" if digits_attr[r][c + 1] < 0 else display_attr[c + 1]
            dig = abs(int(digits_attr[r][c + 1]))
        text = format_c_vector(
            [val], format=fmt, digits=dig, decimal_mark=decimal_mark
        )[0]
        sn = sanitize_numbers(
            Strings([text]),
            type=type_,
            math_style_negative=math_style_negative,
            math_style_exponents=math_style_exponents,
        )
        if isinstance(sn, Strings):
            return "" if sn[0] is NA else str(sn[0])
        return text
    if sanitize_text_function is None:
        return _as_strings([str(val)], type_)[0]
    return str(sanitize_text_function([str(val)])[0])


def print_xtable(
    x: Xtable,
    *,
    type: str = "latex",
    comment: bool = True,
    floating: bool = True,
    floating_environment: str = "table",
    table_placement: str = "ht",
    latex_environments: list[str] | None = None,
    tabular_environment: str = "tabular",
    hline_after: list[int] | None = None,
    na_string: str = "",
    include_rownames: bool = True,
    include_colnames: bool = True,
    only_contents: bool = False,
    sanitize_text_function: Any = None,
    sanitize_rownames_function: Any = None,
    sanitize_colnames_function: Any = None,
    math_style_negative: bool = False,
    math_style_exponents: bool = False,
    print_results: bool = False,
    format_args: dict | None = None,
    booktabs: bool = False,
    timestamp: str | None = "",
    **_: Any,
) -> str:
    if not isinstance(x, Xtable):
        raise ValueError("print.xtable expects an xtable object")
    type = type.lower()
    if type not in ("latex", "html"):
        raise ValueError('"type" must be in {"latex", "html"}')
    if type != "latex":
        raise NotImplementedError("html print.xtable is not ported in this module")

    if latex_environments is None:
        latex_environments = ["center"]
    if hline_after is None:
        hline_after = [-1, 0, x.nrow]
    if format_args is None:
        format_args = {}
    decimal_mark = format_args.get("decimal.mark", ".")

    align = _align_attr(x)
    tmp_index_start = 1
    if not include_rownames:
        while tmp_index_start <= len(align) and align[tmp_index_start - 1] == "|":
            tmp_index_start += 1
        tmp_index_start += 1
    align_spec = "".join(align[tmp_index_start - 1 :])

    varying_digits = isinstance(_digits_attr(x), list) and bool(
        _digits_attr(x) and isinstance(_digits_attr(x)[0], list)
    )
    digits_attr = _digits_attr(x)
    display_attr = _display_attr(x)

    lines: list[str] = []
    if comment:
        lines.append(f"% {type} table generated by xtable")
        if timestamp:
            lines.append(f"% {timestamp}")

    if not only_contents and floating:
        placement = f"[{table_placement}]" if table_placement else ""
        lines.append(f"\\begin{{{floating_environment}}}{placement}")
        if latex_environments and "center" in latex_environments:
            lines.append("\\centering")

    lines.append(f"\\begin{{{tabular_environment}}}{{{align_spec}}}")
    if -1 in hline_after and not booktabs:
        lines.append("  \\hline")

    if include_colnames:
        if sanitize_colnames_function is None:
            cnames = _as_strings(x.colnames(), type)
        else:
            cnames = list(sanitize_colnames_function(x.colnames()))
        if include_rownames:
            header = " & " + " & ".join(cnames) + " \\\\ "
        else:
            header = " & ".join(cnames) + " \\\\ "
        lines.append(header)
        if 0 in hline_after and not booktabs:
            lines.append("  \\hline")
    elif 0 in hline_after and not booktabs:
        lines.append("  \\hline")

    for r in range(x.nrow):
        cells: list[str] = []
        if include_rownames:
            if sanitize_rownames_function is None:
                rname = _as_strings([x.rownames()[r]], type)[0]
            else:
                rname = str(sanitize_rownames_function([x.rownames()[r]])[0])
            cells.append(rname)
        for c in range(x.ncol):
            cells.append(
                _format_cell(
                    x,
                    r,
                    c,
                    type_=type,
                    varying_digits=varying_digits,
                    digits_attr=digits_attr,
                    display_attr=display_attr,
                    decimal_mark=decimal_mark,
                    na_string=na_string,
                    sanitize_text_function=sanitize_text_function,
                    math_style_negative=math_style_negative,
                    math_style_exponents=math_style_exponents,
                )
            )
        prefix = "  " if r > 0 else ""
        lines.append(prefix + " & ".join(cells) + " \\\\ ")

    if x.nrow in hline_after and not booktabs:
        lines.append("   \\hline")

    lines.append(f"\\end{{{tabular_environment}}}")

    if not only_contents and floating:
        lines.append(f"\\end{{{floating_environment}}}")

    result = "\n".join(lines) + "\n"
    if print_results:
        print(result, end="")
    return result
