import statistics
import time

from digest.sha1 import sha1_digest


def one():
    return sha1_digest(None)


value = one()
elapsed = []
for _ in range(20):
    started = time.perf_counter()
    one()
    elapsed.append((time.perf_counter() - started) * 1000)
print(value)
print("%.17g" % statistics.median(elapsed))
