library(mclust)
dir.create("packages/mclust/proof/plot_density_input", recursive=TRUE, showWarnings=FALSE)
set.seed(11)
data <- matrix(c(-2.1,-1.8,-1.2,-0.9,0.8,1.1,1.5,2.0), ncol=1)
object <- densityMclust(data, G=2, modelNames="V")
write.table(object$data, "packages/mclust/proof/plot_density_input/data1.csv", row.names=FALSE, col.names=FALSE, sep=",")
write.table(object$parameters$mean, "packages/mclust/proof/plot_density_input/mean1.csv", row.names=FALSE, col.names=FALSE, sep=",")
write.table(object$parameters$pro, "packages/mclust/proof/plot_density_input/pro1.csv", row.names=FALSE, col.names=FALSE, sep=",")
