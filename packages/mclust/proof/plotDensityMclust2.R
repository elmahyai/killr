library(mclust)
dir.create("packages/mclust/proof/plot_density_input", recursive=TRUE, showWarnings=FALSE)
set.seed(12)
data <- rbind(c(-1.5,-1.1), c(-1.1,-.7), c(.8,1.2), c(1.2,.7), c(1.7,1.4), c(2.0,.9))
object <- densityMclust(data, G=2, modelNames="EEE")
write.table(object$data, "packages/mclust/proof/plot_density_input/data2.csv", row.names=FALSE, col.names=FALSE, sep=",")
write.table(object$parameters$mean, "packages/mclust/proof/plot_density_input/mean2.csv", row.names=FALSE, col.names=FALSE, sep=",")
write.table(object$parameters$pro, "packages/mclust/proof/plot_density_input/pro2.csv", row.names=FALSE, col.names=FALSE, sep=",")
for (g in seq_len(object$G))
  write.table(object$parameters$variance$sigma[,,g], sprintf("packages/mclust/proof/plot_density_input/sigma2_%d.csv",g), row.names=FALSE, col.names=FALSE, sep=",")
out <- surfacePlot(object$data, parameters=object$parameters, grid=40, type="contour", nlevels=7)
write.table(out$x, "packages/mclust/proof/plot_density_input/x2.csv", row.names=FALSE, col.names=FALSE, sep=",")
write.table(out$y, "packages/mclust/proof/plot_density_input/y2.csv", row.names=FALSE, col.names=FALSE, sep=",")
write.table(out$z, "packages/mclust/proof/plot_density_input/z2.csv", row.names=FALSE, col.names=FALSE, sep=",")
write.table(pretty(out$z, n=7), "packages/mclust/proof/plot_density_input/levels2.csv", row.names=FALSE, col.names=FALSE, sep=",")
one <- function() plotDensityMclust2(object, nlevels=7, grid=40)
one()
