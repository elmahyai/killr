def flat(x):
    array = np.asarray(x, dtype=np.float64).reshape(-1)
    if array.size == 0:
        return ""

    def fmt(v):
        value = float(v)
        if math.isnan(value):
            return "NA"
        if math.isinf(value):
            return "Inf" if value > 0 else "-Inf"
        return format(value, ".16g")

    return "|".join(fmt(v) for v in array)


