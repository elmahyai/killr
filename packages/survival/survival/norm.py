"""Standard normal quantile, from R's qnorm (AS 241)."""

import math

_SQRT2 = math.sqrt(2.0)
_2PI = 2.0 * math.pi


def qnorm(p, mu=0.0, sigma=1.0):
    """Lower-tail normal quantile. p outside (0, 1) follows R's boundaries."""
    if math.isnan(p) or math.isnan(mu) or math.isnan(sigma):
        return p + mu + sigma
    if p <= 0.0:
        return math.nan if p < 0.0 else -math.inf
    if p >= 1.0:
        return math.nan if p > 1.0 else math.inf
    if sigma < 0.0:
        return math.nan
    if sigma == 0.0:
        return mu
    q = p - 0.5
    if abs(q) <= 0.425:
        r = 0.180625 - q * q
        val = (
            q
            * (
                (
                    (
                        (
                            (
                                ((r * 2509.0809287301226727 + 33430.575583588128105) * r + 67265.770927008700853)
                                * r
                                + 45921.953931549871457
                            )
                            * r
                            + 13731.693765509461125
                        )
                        * r
                        + 1971.5909503065514427
                    )
                    * r
                    + 133.14166789178437745
                )
                * r
                + 3.387132872796366608
            )
            / (
                (
                    (
                        (
                            (
                                ((r * 5226.495278852854561 + 28729.085735721942674) * r + 39307.89580009271061)
                                * r
                                + 21213.794301586595867
                            )
                            * r
                            + 5394.1960214247511077
                        )
                        * r
                        + 687.1870074920579083
                    )
                    * r
                    + 42.313330701600911252
                )
                * r
                + 1.0
            )
        )
    else:
        lp = math.log((1.0 - p) if q > 0.0 else p)
        r = math.sqrt(-lp)
        if r <= 5.0:
            r += -1.6
            val = (
                (
                    (
                        (
                            (
                                (
                                    ((r * 7.7454501427834140764e-4 + 0.0227238449892691845833) * r + 0.24178072517745061177)
                                    * r
                                    + 1.27045825245236838258
                                )
                                * r
                                + 3.64784832476320460504
                            )
                            * r
                            + 5.7694972214606914055
                        )
                        * r
                        + 4.6303378461565452959
                    )
                    * r
                    + 1.42343711074968357734
                )
                / (
                    (
                        (
                            (
                                (
                                    (
                                        ((r * 1.05075007164441684324e-9 + 5.475938084995344946e-4) * r + 0.0151986665636164571966)
                                        * r
                                        + 0.14810397642748007459
                                    )
                                    * r
                                    + 0.68976733498510000455
                                )
                                * r
                                + 1.6763848301838038494
                            )
                            * r
                            + 2.05319162663775882187
                        )
                        * r
                        + 1.0
                    )
                )
            )
        elif r <= 27.0:
            r += -5.0
            val = (
                (
                    (
                        (
                            (
                                (
                                    ((r * 2.01033439929228813265e-7 + 2.71155556874348757815e-5) * r + 0.0012426609473880784386)
                                    * r
                                    + 0.026532189526576123093
                                )
                                * r
                                + 0.29656057182850489123
                            )
                            * r
                            + 1.7848265399172913358
                        )
                        * r
                        + 5.4637849111641143699
                    )
                    * r
                    + 6.6579046435011037772
                )
                / (
                    (
                        (
                            (
                                (
                                    (
                                        ((r * 2.04426310338993978564e-15 + 1.4215117583164458887e-7) * r + 1.8463183175100546818e-5)
                                        * r
                                        + 7.868691311456132591e-4
                                    )
                                    * r
                                    + 0.0148753612908506148525
                                )
                                * r
                                + 0.13692988092273580531
                            )
                            * r
                            + 0.59983220655588793769
                        )
                        * r
                        + 1.0
                    )
                )
            )
        else:
            if r >= 6.4e8:
                val = r * _SQRT2
            else:
                s2 = -math.ldexp(lp, 1)
                x2 = s2 - math.log(_2PI * s2)
                if r < 36000.0:
                    x2 = s2 - math.log(_2PI * x2) - 2.0 / (2.0 + x2)
                    if r < 840.0:
                        x2 = s2 - math.log(_2PI * x2) + 2 * math.log1p(-(1 - 1 / (4 + x2)) / (2.0 + x2))
                        if r < 109.0:
                            x2 = s2 - math.log(_2PI * x2) + 2 * math.log1p(
                                -(1 - (1 - 5 / (6 + x2)) / (4.0 + x2)) / (2.0 + x2)
                            )
                            if r < 55.0:
                                x2 = s2 - math.log(_2PI * x2) + 2 * math.log1p(
                                    -(1 - (1 - (5 - 9 / (8.0 + x2)) / (6.0 + x2)) / (4.0 + x2)) / (2.0 + x2)
                                )
                val = math.sqrt(x2)
        if q < 0.0:
            val = -val
    return mu + sigma * val
